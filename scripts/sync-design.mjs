// Copies the design system (packages/design) into each Next.js app, because the apps
// don't import workspace packages on Vercel. Run after editing anything in packages/design:
//   node scripts/sync-design.mjs
// Writes, per app:
//   src/design/tokens.ts, src/design/tailwind-preset.ts, src/design/tokens.css (generated)
//   src/components/ds/*  (shared React components)
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages/design");
const apps = ["apps/patient-web", "apps/provider-web", "apps/admin"];
const header = "// GENERATED by scripts/sync-design.mjs. Edit packages/design, then re-run the script.\n";

// Node 22.6+ strips the types when importing a .ts file
const { colors, radius, shadow, spacing, fontSize, accent, fontStack } = await import(
  pathToFileURL(join(src, "tokens.ts")).href
);

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");
const accentVars = (set) => Object.entries(set).map(([k, v]) => `  --${k}-rgb: ${rgb(v)};`).join("\n");
const vars = (prefix, obj, rename = {}) =>
  Object.entries(obj).map(([k, v]) => `  --${prefix}${rename[k] ?? k}: ${v};`.replace("--radius-:", "--radius:").replace("--shadow-:", "--shadow:"));

const css = `/* GENERATED by scripts/sync-design.mjs from packages/design/tokens.ts. Do not edit. */
/* StreetdocMD design tokens. Light theme only: there are no dark-mode rules. */
:root {
${vars("", colors).join("\n")}

${vars("radius-", radius, { md: "" }).join("\n")}

${vars("shadow-", shadow, { md: "" }).join("\n")}

${vars("", spacing).join("\n")}

${vars("fs-", fontSize).join("\n")}

  --font: ${fontStack.join(", ")};

  /* Accent used by the components: blue by default */
${accentVars(accent.default)}

  color-scheme: light;
}

/* Provider app (and facility portals): teal replaces blue as the accent */
.theme-provider {
${accentVars(accent.provider)}
}
`;

const componentDir = join(src, "components");
const components = readdirSync(componentDir).filter((f) => /\.tsx?$/.test(f));

for (const app of apps) {
  const designDir = join(root, app, "src/design");
  const dsDir = join(root, app, "src/components/ds");
  mkdirSync(designDir, { recursive: true });
  mkdirSync(dsDir, { recursive: true });

  for (const f of ["tokens.ts", "tailwind-preset.ts"]) writeFileSync(join(designDir, f), header + readFileSync(join(src, f), "utf8"));
  writeFileSync(join(designDir, "tokens.css"), css);
  for (const f of components) writeFileSync(join(dsDir, f), header + readFileSync(join(componentDir, f), "utf8"));

  console.log(`synced tokens + ${components.length} component files → ${app}`);
}
