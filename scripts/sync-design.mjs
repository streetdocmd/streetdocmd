// Copies the design system (packages/design) into each Next.js app, because the apps
// don't import workspace packages on Vercel. Run after editing anything in packages/design:
//   node scripts/sync-design.mjs
// Writes, per app:
//   src/design/tokens.ts, src/design/tailwind-preset.ts, src/design/tokens.css (generated)
//   src/components/ds/*  (shared React components)
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages/design");
const apps = ["apps/patient-web", "apps/provider-web", "apps/admin"];
const header = "// GENERATED by scripts/sync-design.mjs. Edit packages/design, then re-run the script.\n";

// Node 22.6+ strips the types when importing a .ts file
const { PALETTES, SHADES, colors, legacy, dark, darkBase, darkAccent, darkShadow, radius, shadow, spacing, fontSize, accent, fontStack } = await import(
  pathToFileURL(join(src, "tokens.ts")).href
);
const tw = createRequire(import.meta.url)("tailwindcss/colors");

const hexRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const rgb = (hex) => hexRgb(hex).join(" ");
const toHex = (arr) => "#" + arr.map((n) => Math.round(n).toString(16).padStart(2, "0")).join("");
// t = how far toward the dark surface
const mix = (hex, t) => { const a = hexRgb(hex), b = hexRgb(darkBase); return toHex(a.map((x, i) => x * (1 - t) + b[i] * t)); };
const vars = (prefix, obj, rename = {}) =>
  Object.entries(obj).map(([k, v]) => `  --${prefix}${rename[k] ?? k}: ${v};`.replace("--radius-:", "--radius:").replace("--shadow-:", "--shadow:"));

// Light: every role is the same colour
const light = { ...colors, ...legacy };
for (const p of PALETTES) for (const s of SHADES) light[`${p}-${s}`] = tw[p][s];

// Dark: tokens from tokens.ts; Tailwind palettes by rule. Light tints become
// dark tints for fills, strong shades become lighter for text, and light
// borders become dark lines. Strong fills keep their colour so white text on
// them stays readable.
const darkRoles = {};
for (const [k, r] of Object.entries(dark)) darkRoles[k] = r;
for (const p of PALETTES) {
  const P = tw[p];
  const fill = { 50: mix(P[900], 0.72), 100: mix(P[900], 0.6), 200: mix(P[800], 0.55), 300: mix(P[700], 0.45) };
  const text = { 500: P[400], 600: P[400], 700: P[300], 800: P[200], 900: P[200], 950: P[100] };
  const line = { 50: mix(P[800], 0.6), 100: mix(P[800], 0.5), 200: mix(P[700], 0.55), 300: mix(P[600], 0.5) };
  for (const s of SHADES) {
    const r = {};
    if (fill[s]) r.c = fill[s];
    if (text[s]) r.t = text[s];
    if (line[s]) r.b = line[s];
    darkRoles[`${p}-${s}`] = r;
  }
}

const roleVars = (name, hex) => ["c", "t", "b"].map((r) => `  --${r}-${name}: ${rgb(hex)};`).join("\n");
const darkVars = (name, roles) =>
  Object.entries(roles).map(([r, hex]) => `  --${r}-${name}: ${rgb(hex)};`).join("\n");
const accentLight = (set) => Object.entries(set).map(([k, v]) => roleVars(k, v)).join("\n");
const accentDark = (set) => Object.entries(set).map(([k, roles]) => darkVars(k, roles)).join("\n");

const css = `/* GENERATED by scripts/sync-design.mjs from packages/design/tokens.ts. Do not edit. */
/* StreetdocMD design tokens. Light by default; the dark class on <html> switches to the dark theme. */
:root {
${vars("", colors).join("\n")}

${vars("radius-", radius, { md: "" }).join("\n")}

${vars("shadow-", shadow, { md: "" }).join("\n")}

${vars("", spacing).join("\n")}

${vars("fs-", fontSize).join("\n")}

  --font: ${fontStack.join(", ")};

  /* Colour roles read by the Tailwind preset: c = fills, t = text, b = borders */
${Object.entries(light).map(([k, v]) => roleVars(k, v)).join("\n")}

  /* Accent used by the components: blue by default */
${accentLight(accent.default)}

  color-scheme: light;
}

/* Provider app (and facility portals): teal replaces blue as the accent */
.theme-provider {
${accentLight(accent.provider)}
}

.dark {
  color-scheme: dark;
${Object.entries(dark).filter(([k, r]) => r.c && k in colors).map(([k, r]) => `  --${k}: ${r.c};`).join("\n")}
${vars("shadow-", darkShadow, { md: "" }).join("\n")}
${Object.entries(darkRoles).map(([k, r]) => darkVars(k, r)).filter(Boolean).join("\n")}
${accentDark(darkAccent.default)}
}

.dark .theme-provider,
.dark.theme-provider {
${accentDark(darkAccent.provider)}
}

/* Solid and nearly solid white fills are card surfaces, so they turn dark.
   Faint white overlays (bg-white/10 on a navy panel) stay white. */
.dark .bg-white,
.dark .hover\\:bg-white:hover { background-color: rgb(var(--c-surface)); }
${[60, 70, 80, 90, 95].map((a) => `.dark .bg-white\\/${a} { background-color: rgb(var(--c-surface) / ${a / 100}); }`).join("\n")}
`;

const componentDir = join(src, "components");
const components = readdirSync(componentDir).filter((f) => /\.tsx?$/.test(f));

for (const app of apps) {
  const designDir = join(root, app, "src/design");
  const dsDir = join(root, app, "src/components/ds");
  mkdirSync(designDir, { recursive: true });
  mkdirSync(dsDir, { recursive: true });

  for (const f of ["tokens.ts", "tailwind-preset.ts"]) writeFileSync(join(designDir, f), header + readFileSync(join(src, f), "utf8"));
  writeFileSync(join(designDir, "tokens.css"), css);
  for (const f of components) writeFileSync(join(dsDir, f), header + readFileSync(join(componentDir, f), "utf8"));

  console.log(`synced tokens + ${components.length} component files → ${app}`);
}
