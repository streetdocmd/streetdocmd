// Copies the legal documents (packages/shared/src/legal) into apps that don't import
// @streetdocmd/shared on Vercel. Run after editing any legal text:  node scripts/sync-legal.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages/shared/src/legal");
const targets = ["apps/landing-page/lib/legal", "apps/patient-web/src/lib/legal", "apps/admin/src/lib/legal"];
const header = "// GENERATED by scripts/sync-legal.mjs. Edit packages/shared/src/legal, then re-run the script.\n";

const files = {
  "types.ts": join(src, "types.ts"),
  "privacy-policy.ts": join(src, "privacy-policy.ts"),
  "patient-terms.ts": join(src, "patient-terms.ts"),
  "facility-agreement.ts": join(src, "facility-agreement.ts"),
  "provider-agreement.ts": join(src, "provider-agreement.ts"),
  "index.ts": join(src, "index.ts"),
  // the shared copy is a re-export; apps get the full text
  "provider-agreement-source.ts": join(root, "packages/shared/src/constants/provider-agreement.ts"),
};

for (const t of targets) {
  const dir = join(root, t);
  mkdirSync(dir, { recursive: true });
  for (const [name, from] of Object.entries(files)) writeFileSync(join(dir, name), header + readFileSync(from, "utf8"));
  console.log(`synced ${Object.keys(files).length} files → ${t}`);
}
